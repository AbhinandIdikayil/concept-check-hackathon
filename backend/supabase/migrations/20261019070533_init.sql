-- Concept Check: base schema.
--
-- Idempotent, so it is safe to run against a project that already has these
-- tables.
--
--   psql "$SUPABASE_DB_URL" -f supabase/migrations/20261019070533_init.sql
--   npx supabase db push     (run from backend/, the folder holding supabase/)
--
-- Use the session pooler host on port 5432:
--   postgresql://postgres.<ref>:<DB_PASSWORD>@aws-0-<region>.pooler.supabase.com:5432/postgres
-- db.<ref>.supabase.co is IPv6 only and will fail on an IPv4-only network.

create table if not exists public.cases (
  id   varchar primary key,                                     -- '1'..'6' seeded, ULID for LLM written
  text text not null                                         -- the question
);

create table if not exists public.answers (
  id      uuid primary key default gen_random_uuid(),
  case_id varchar not null references public.cases(id) on delete cascade,
  answer  text not null                                      -- the reference answer
);

create table if not exists public.chats (
  id         uuid primary key default gen_random_uuid(),     -- generated by the database
  user_id    text not null,                                  -- ULID, one per browser
  case_id    varchar not null references public.cases(id),
  created_at timestamptz not null default now(),
  ended_at   timestamptz
);

-- Enum types. Postgres has no CREATE TYPE IF NOT EXISTS, so the creation is
-- guarded by a DO block to keep this migration re-runnable.
-- Values must stay in sync with the Literal[...] types in app/models.py.
do $$
begin
  if not exists (
    select 1 from pg_type t
    join pg_namespace n on n.oid = t.typnamespace
    where t.typname = 'message_role' and n.nspname = 'public'
  ) then
    create type public.message_role as enum ('user', 'assistant');
  end if;

  if not exists (
    select 1 from pg_type t
    join pg_namespace n on n.oid = t.typnamespace
    where t.typname = 'message_status' and n.nspname = 'public'
  ) then
    create type public.message_status as enum ('success', 'recite');
  end if;
end;
$$;

create table if not exists public.messages (
  id         uuid primary key default gen_random_uuid(),
  chat_id    uuid not null references public.chats(id) on delete cascade,
  role       public.message_role not null,
  message    text not null,
  status     public.message_status,                          -- null until the answer is graded
  created_at timestamptz not null default now()
);

-- Exactly one reference answer per case. The unique index also gives the seed
-- migration an ON CONFLICT target.
drop index if exists public.answers_case_id_idx;
create unique index if not exists answers_case_id_key on public.answers (case_id);

create index if not exists messages_chat_id_created_at_idx on public.messages (chat_id, created_at);
create index if not exists chats_user_id_idx on public.chats (user_id);
create index if not exists chats_case_id_idx on public.chats (case_id);

alter table public.cases    enable row level security;
alter table public.answers  enable row level security;
alter table public.chats    enable row level security;
alter table public.messages enable row level security;

